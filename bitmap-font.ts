function lookup(letter: string): Glyph {
  const glyph = glyphs.get(letter);
  if (!glyph) throw new Error(`No bitmap glyph for ${JSON.stringify(letter)}`);
  return glyph;
}

// Sizes name the em, not the cap height. Snap edges in page coordinates,
// not each character's advance, to keep measuring and drawing in agreement.
export function textWidth(text: string, size: number): number {
  let cells = -1;
  for (const letter of text.normalize('NFC')) cells += lookup(letter).width + 1;
  return Math.round(Math.max(0, cells) * size / 9);
}

export function drawText(fill: Fill, text: string, x: number, y: number, size: number): void {
  const step = size / 9;
  if (step < 1) throw new Error('Bitmap text cannot be rendered below 9 px');
  let advance = 0;
  for (const letter of text.normalize('NFC')) {
    const { width, rows, top } = lookup(letter);
    for (const [rowIndex, row] of rows.entries()) {
      const rowY = Math.round(y + (top + rowIndex) * step);
      const height = Math.round(y + (top + rowIndex + 1) * step) - rowY;
      for (let col = 0; col < width; col++) {
        if (row[col] !== '#') continue;
        const left = Math.round(x + (advance + col) * step);
        const right = Math.round(x + (advance + col + 1) * step);
        fill(left, rowY, right - left, height);
      }
    }
    advance += width + 1;
  }
}
